const fs = require('node:fs');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const baseline = JSON.parse(fs.readFileSync('scripts/merged-home-baseline.json', 'utf8'));
const html = fs.readFileSync('index.html', 'utf8');
const body = html.match(/<body\b[^>]*>([\s\S]*?)<\/body>/i)[1];
const text = [...('<body>' + body + '</body>').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, '').replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, '').matchAll(/>([^<]+)</g)].map(m => m[1].trim()).filter(Boolean).sort();
const scripts = [...html.matchAll(/<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)].map(m => crypto.createHash('sha256').update(m[1]).digest('hex'));
assert.deepEqual(text, baseline.text, 'Original hub text changed');
assert.deepEqual(scripts, baseline.inlineScripts, 'Original hub data or business logic changed');
assert.ok(html.includes('class="home-video"') && !html.includes('main.tsx'));
assert.ok(fs.readFileSync('index_hub.html', 'utf8').includes('location.replace'));
console.log('PASS: unified static homepage preserves every original hub text node and inline script, including all course data and learning handlers; old URL redirects.');
